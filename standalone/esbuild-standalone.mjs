#!/usr/bin/env node

// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
// Standalone Bundle Builder
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
//
// Bundles the TypeScript source (AgentClient + handlers) into
// a single zero-dependency ESM file using esbuild.
//
// The output is standalone/workspace-agent-core.mjs — the same
// file consumed by the tray app and CLI wrapper.
//
// Shims:
//   • ws → standalone/shims/ws-shim.mjs (built-in WebSocket)
//   • src/logger.ts → standalone/shims/logger-shim.mjs (injectable)
//
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

import { build } from "esbuild";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { readFileSync } from "node:fs";

const currentDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(currentDirectory, "..");
const entryPoint = resolve(currentDirectory, "bundle-entry.mjs");
const outputFile = resolve(currentDirectory, "workspace-agent-core.mjs");
const wsShimPath = resolve(currentDirectory, "shims/ws-shim.mjs");
const loggerShimPath = resolve(currentDirectory, "shims/logger-shim.mjs");

console.log("━━━ Building Standalone Bundle ━━━");
console.log(`  Entry:  ${entryPoint}`);
console.log(`  Output: ${outputFile}`);

// ── esbuild alias plugin ──────────────────────────────────────
// Redirects `ws` and the logger imports to our standalone shims.

const aliasPlugin = {
  name: "standalone-alias",
  setup(pluginBuild) {
    // Replace `import WebSocket from "ws"` with the built-in WS shim
    pluginBuild.onResolve({ filter: /^ws$/ }, () => ({
      path: wsShimPath,
    }));

    // Replace `import logger from "../logger.ts"` (any depth) with injectable shim
    pluginBuild.onResolve({ filter: /logger\.ts$/ }, (arguments_) => {
      // Only intercept the workspace-service logger, not other loggers
      if (arguments_.importer.includes("workspace-service/src")) {
        return { path: loggerShimPath };
      }
      return undefined;
    });

    // Replace `import { createLogger } from "@rodrigo-barraza/utilities-library/node"`
    // This is used by logger.ts, which we already shim. But in case it leaks:
    pluginBuild.onResolve(
      { filter: /^@rodrigo-barraza\/utilities-library\/node$/ },
      () => ({
        path: loggerShimPath,
      }),
    );

    // Replace vault bootstrap (not needed in standalone mode)
    pluginBuild.onResolve(
      { filter: /^@rodrigo-barraza\/utilities-library\/vault$/ },
      () => ({
        path: resolve(currentDirectory, "shims/empty-shim.mjs"),
        external: false,
      }),
    );

    // Replace MongoDB (not needed in standalone mode)
    pluginBuild.onResolve(
      { filter: /^@rodrigo-barraza\/utilities-library\/mongo$/ },
      () => ({
        path: resolve(currentDirectory, "shims/empty-shim.mjs"),
        external: false,
      }),
    );
  },
};

try {
  const result = await build({
    entryPoints: [entryPoint],
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node26",
    outfile: outputFile,
    external: [
      // All Node.js built-in modules stay external
      "node:*",
    ],
    plugins: [aliasPlugin],
    // Preserve readable output (not minified)
    minify: false,
    // Tree-shake unused exports
    treeShaking: true,
    // Generate a banner comment
    banner: {
      js: [
        "#!/usr/bin/env node",
        "",
        "// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━",
        "// Workspace Agent Core — AUTO-GENERATED BUNDLE",
        "// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━",
        "//",
        "//  DO NOT EDIT THIS FILE MANUALLY.",
        "//  It is generated by: node standalone/esbuild-standalone.mjs",
        "//  Source of truth: src/AgentClient.ts + src/handlers/*",
        "//",
        `//  Generated: ${new Date().toISOString()}`,
        "//",
        "// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━",
        "",
      ].join("\n"),
    },
    // Log level
    logLevel: "info",
  });

  // ── Post-build verification ───────────────────────────────────
  const generatedSource = readFileSync(outputFile, "utf-8");

  // Verify critical exports exist
  const requiredExports = ["WorkspaceAgent", "setLogger", "hostname"];
  const missingExports = requiredExports.filter(
    (exportName) => !generatedSource.includes(exportName),
  );
  if (missingExports.length > 0) {
    console.error(`\n❌ Missing exports: ${missingExports.join(", ")}`);
    process.exit(1);
  }

  // Verify all RPC methods from AgentClient.ts are present
  const expectedMethods = [
    "file.read",
    "file.write",
    "file.strReplace",
    "file.patch",
    "file.info",
    "file.diff",
    "file.move",
    "file.delete",
    "file.readMulti",
    "directory.list",
    "directory.create",
    "directory.tree",
    "search.grep",
    "search.glob",
    "git.status",
    "git.diff",
    "git.log",
    "command.run",
    "command.stream",
    "project.summary",
    "watch.subscribe",
    "watch.unsubscribe",
  ];

  const missingMethods = expectedMethods.filter(
    (method) => !generatedSource.includes(`"${method}"`),
  );
  if (missingMethods.length > 0) {
    console.error(`\n❌ Missing RPC methods in bundle: ${missingMethods.join(", ")}`);
    process.exit(1);
  }

  // Count output lines
  const lineCount = generatedSource.split("\n").length;

  console.log(`\n✅ Bundle generated successfully`);
  console.log(`   ${lineCount} lines`);
  console.log(`   ${expectedMethods.length} RPC methods verified`);
  console.log(`   ${requiredExports.length} exports verified`);

  if (result.warnings.length > 0) {
    console.warn(`\n⚠ ${result.warnings.length} warning(s):`);
    for (const warning of result.warnings) {
      console.warn(`  ${warning.text}`);
    }
  }
} catch (error) {
  console.error(`\n❌ Build failed: ${error.message}`);
  process.exit(1);
}
